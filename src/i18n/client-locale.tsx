export type MessageKey = keyof typeof messages.en;
interface LocaleState {
  locale: Locale;
  setLocale: (locale: Locale) => Promise<void>;
}

const LocaleContext = createContext<LocaleState | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setCurrentLocale] = useState<Locale>(defaultLocale);

  useEffect(() => {
    const cookieLocale = document.cookie
      .split('; ')
      .find((part) => part.startsWith('NEXT_LOCALE='))
      ?.split('=')[1];
    const decodedLocale = cookieLocale ? decodeURIComponent(cookieLocale) : null;
    if (decodedLocale && isLocale(decodedLocale)) setCurrentLocale(decodedLocale);
  }, []);

  const setLocale = useCallback(async (next: Locale) => {
    const response = await fetch('/api/locale', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({ locale: next }),
    });
    if (!response.ok) throw new Error('Could not update language.');
    setCurrentLocale(next);
  }, []);

  const value = useMemo<LocaleState>(() => ({ locale, setLocale }), [locale, setLocale]);
  return (
    <LocaleContext.Provider value={value}>
      <IntlProvider locale={locale} messages={messages[locale]}>
        {children}
      </IntlProvider>
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  const translate = useTranslations();
  if (!context) throw new Error('useLocale must be used within LocaleProvider');
  return { ...context, t: (key: MessageKey) => translate(key) };
}
